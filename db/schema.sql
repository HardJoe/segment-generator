CREATE TABLE IF NOT EXISTS nodes (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id SMALLINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    name TEXT NOT NULL UNIQUE,
    value INTEGER NULL
);

CREATE TABLE IF NOT EXISTS connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_port_id BIGINT NOT NULL UNIQUE REFERENCES ports(id) ON DELETE CASCADE,
    target_port_id BIGINT NOT NULL UNIQUE REFERENCES ports(id) ON DELETE CASCADE,
    CONSTRAINT connections_distinct_ports CHECK (source_port_id <> target_port_id)
);
